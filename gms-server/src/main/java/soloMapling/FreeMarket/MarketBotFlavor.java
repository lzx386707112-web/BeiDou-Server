    public static String chat() {
        int roll = ThreadLocalRandom.current().nextInt(100);
        if (roll < 50) {
            return pickFresh(CHAT);
        }
        if (roll < 68) {
            return pickFresh(WANDER);
        }
        if (roll < 80) {
            return pickFresh(FUNNY);
        }
        if (roll < 88) {
            return pickFresh(SCAM);
        }
        if (roll < 94) {
            return pickFresh(WARN);
        }
        return pickFresh(BEG);
    }

