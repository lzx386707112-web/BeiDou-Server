    private static String pick(String[] pool) {
        return pool[ThreadLocalRandom.current().nextInt(pool.length)];
    }

    private static synchronized String pickFresh(String[] pool) {
        String line = pick(pool);
        if (pool.length > 1) {
            for (int i = 0; i < 16 && RECENT_LINES.contains(line); i++) {
                line = pick(pool);
            }
        }
        RECENT_LINES.addLast(line);
        while (RECENT_LINES.size() > RECENT) {
            RECENT_LINES.removeFirst();
        }
        return line;
    }
