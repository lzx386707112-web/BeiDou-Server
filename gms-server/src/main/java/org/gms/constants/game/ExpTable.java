    /**
     * 获取升级所需经验.客户端在超过1697021059后显示2147483647
     *
     * @param level 等级
     * @return 所需经验，如果等级超出数组范围，则返回最后一个等级所需的经验
     */
    public static int getExpNeededForLevel(int level) {
        return getExpNeededForLevel(level, 0);
    }

    public static int getExpNeededForLevel(int level, int rebornsCount) {
        // 如果 level 大于等于数组长度，Math.min 会返回 array.length - 1（即最后一个元素的索引）
        // 如果 level 为负数，数组会抛出 ArrayIndexOutOfBoundsException，这通常是非法输入，应该避免
        if (rebornsCount > 0 && level > 200) {
            //一次转生后固定21E升一级
            return 2100000000;
        } else {
            int safeIndex = Math.min(level, exp.length - 1);
            return exp[safeIndex];
        }
        //        return level > 200 ? 2000000000 : exp[level];
    }

    public static int getMaxLevelExpLimit(int level, int rebornsCount) {
        return (int) ((long) getExpNeededForLevel(level, rebornsCount) * MAX_LEVEL_EXP_PERCENT / 100);
    }

    public static float getPostLevel200ExpRate(int level) {
        if (level <= LEVEL_EXP_DECAY_START) {
            return 1.0f;
        }

        float rate = 1.0f - (level - LEVEL_EXP_DECAY_START) * LEVEL_EXP_DECAY_PER_LEVEL;
        return Math.max(MIN_LEVEL_EXP_RATE, rate);
    }

