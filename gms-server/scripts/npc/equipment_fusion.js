function start() {
    status = -1;
    action(1, 0, 0);
}
function action(mode, type, selection) {
    if (mode != 1) {
        cm.dispose();
        return;
    }

    status++;

    if (status == 0) {
        showJobs();
    } else if (status == 1) {
        if (!isValidSelection(selection, jobs.length)) {
            cm.dispose();
            return;
        }
        selectedJob = selection;
        showWeaponTypes();
    } else if (status == 2) {
        var types = jobs[selectedJob].types;
        if (!isValidSelection(selection, types.length)) {
            cm.dispose();
            return;
        }
        selectedType = selection;
        showRecipes();
    } else if (status == 3) {
        var recipes = jobs[selectedJob].types[selectedType].recipes;
        if (!isValidSelection(selection, recipes.length)) {
            cm.dispose();
            return;
        }
        selectedRecipe = selection;
        cm.sendYesNo(buildConfirmation(recipes[selectedRecipe]));
    } else if (status == 4) {
        fuse(jobs[selectedJob].types[selectedType].recipes[selectedRecipe]);
        cm.dispose();
    } else {
        cm.dispose();
    }
}

function isValidSelection(selection, size) {
    return selection >= 0 && selection < size;
}

function showJobs() {
    var text = "#e装备融合#n\r\n请选择职业分类：\r\n";
    for (var i = 0; i < jobs.length; i++) {
        text += "\r\n#L" + i + "##b" + jobs[i].name + "#k#l";
    }
    cm.sendSimple(text);
}

function showWeaponTypes() {
    var types = jobs[selectedJob].types;
    var text = "#e装备融合 - " + jobs[selectedJob].name + "#n\r\n请选择武器类型：\r\n";
    for (var i = 0; i < types.length; i++) {
        text += "\r\n#L" + i + "##b" + types[i].name + "#k#l";
    }
    cm.sendSimple(text);
}

function showRecipes() {
    var weaponType = jobs[selectedJob].types[selectedType];
    var text = "#e装备融合 - " + jobs[selectedJob].name + " / " + weaponType.name + "#n";
    text += "\r\n请选择要融合的目标装备：\r\n";

    for (var i = 0; i < weaponType.recipes.length; i++) {
        var recipe = weaponType.recipes[i];
        text += "\r\n#L" + i + "##v" + recipe[1] + "# #b" + recipe[0] + "级 #z" + recipe[1] + "##k#l";
    }
    cm.sendSimple(text);
}

function buildConfirmation(recipe) {
    var text = "#e融合目标#n\r\n#v" + recipe[1] + "# #b#z" + recipe[1] + "##k";
    text += "（" + recipe[0] + "级）\r\n\r\n#e所需材料#n";

    for (var i = 0; i < recipe[2].length; i++) {
        var materialId = recipe[2][i];
        var owned = cm.getItemQuantity(materialId);
        var color = owned >= 1 ? "#g" : "#r";
        text += "\r\n#v" + materialId + "# #z" + materialId + "# x 1";
        text += " " + color + "（持有 " + owned + "）#k";
    }

    text += "\r\n\r\n融合会消耗以上装备，并获得 1 件目标装备。";
    text += "\r\n装备中的强化、潜能等属性不会继承。是否确认融合？";
    return text;
}

function fuse(recipe) {
    var missing = [];
    var removeQuantities = [];

    for (var i = 0; i < recipe[2].length; i++) {
        var materialId = recipe[2][i];
        if (!cm.haveItem(materialId, 1)) {
            missing.push(materialId);
        }
        removeQuantities.push(1);
    }

    if (missing.length > 0) {
        var text = "#r材料不足，融合未进行。#k\r\n请将所需装备放在装备栏中，穿戴中的装备不计入：";
        for (var j = 0; j < missing.length; j++) {
            text += "\r\n#v" + missing[j] + "# #z" + missing[j] + "# x 1";
        }
        cm.sendOk(text);
        return;
    }

    if (!cm.canHoldAllAfterRemoving([recipe[1]], [1], recipe[2], removeQuantities)) {
        cm.sendOk("#r装备栏空间不足，融合未进行。#k\r\n请整理装备栏后再试。");
        return;
    }

    for (var k = 0; k < recipe[2].length; k++) {
        cm.gainItem(recipe[2][k], -1);
    }
    cm.gainItem(recipe[1], 1);
    cm.sendOk("融合成功！\r\n获得 #v" + recipe[1] + "# #b#z" + recipe[1] + "##k。");
}
