function start() {
    status = -1;
    category = -1;
    catalog = null;
    page = 0;
    action(1, 0, 0);
}

function visibleStock(list) {
    var out = [];
    for (var i = 0; i < list.length; i++) {
        if (cm.canGenerateItem(list[i][0])) {
            out.push(list[i]);
        }
    }
    return out;
}

function sendCatalog() {
    var owned = cm.getItemQuantity(COIN);
    var pages = Math.ceil(catalog.length / PAGE_SIZE);
    if (pages < 1) {
        pages = 1;
    }
    if (page < 0) {
        page = 0;
    }
    if (page >= pages) {
        page = pages - 1;
    }
    var start = page * PAGE_SIZE;
    var end = Math.min(start + PAGE_SIZE, catalog.length);
    var menu = "#e" + CATEGORIES[category] + "#n  余额 #b" + owned + "#k 枚";
    if (pages > 1) {
        menu += "  (" + (page + 1) + "/" + pages + ")";
    }
    menu += "\r\n#b";
    for (var i = start; i < end; i++) {
        menu += "#L" + i + "##v" + catalog[i][0] + "# #t" + catalog[i][0] + "#（" + catalog[i][1] + " 枚）#l\r\n";
    }
    if (page > 0) {
        menu += "#L10000#上一页#l\r\n";
    }
    if (end < catalog.length) {
        menu += "#L10001#下一页#l\r\n";
    }
    cm.sendSimple(menu);
}

function action(mode, type, selection) {
    if (mode <= 0) {
        cm.dispose();
        return;
    }
    status++;
    if (status == 0) {
        var owned = cm.getItemQuantity(COIN);
        var menu = "欢迎光临。这里用#b#t" + COIN + "##k换道具。你现在有 #b" + owned + "#k 枚。\r\n#b";
        for (var i = 0; i < CATEGORIES.length; i++) {
            menu += "#L" + i + "#" + CATEGORIES[i] + "#l\r\n";
        }
        cm.sendSimple(menu);
        return;
    }
    if (status == 1) {
        if (selection < 0 || selection >= STOCK.length) {
            cm.dispose();
            return;
        }
        category = selection;
        catalog = visibleStock(STOCK[category]);
        page = 0;
        if (catalog.length == 0) {
            cm.sendOk("这一类暂时没有能兑换的道具。");
            cm.dispose();
            return;
        }
        sendCatalog();
        return;
    }
    if (catalog == null) {
        cm.dispose();
        return;
    }
    if (selection == 10000) {
        page--;
        status = 1;
        sendCatalog();
        return;
    }
    if (selection == 10001) {
        page++;
        status = 1;
        sendCatalog();
        return;
    }
    if (selection < 0 || selection >= catalog.length) {
        cm.dispose();
        return;
    }
    var itemId = catalog[selection][0];
    var cost = catalog[selection][1];
    if (!cm.canGenerateItem(itemId)) {
        cm.sendOk("该物品数据不存在，暂时无法兑换。");
        cm.dispose();
        return;
    }
    if (!cm.haveItem(COIN, cost)) {
        cm.sendOk("纪念币不够。需要 #b" + cost + "#k 枚。");
        cm.dispose();
        return;
    }
    if (!cm.canHold(itemId, 1)) {
        cm.sendOk("请先空出背包格子。");
        cm.dispose();
        return;
    }
    cm.gainItem(COIN, -cost);
    cm.gainItem(itemId, 1);
    cm.sendOk("谢谢惠顾。拿着#t" + itemId + "#小心点。");
    cm.dispose();
}
