var skins = [0, 1, 2, 3, 4, 9];

function action(mode, type, selection) {
    if (mode === -1) {
        cm.dispose();
        return;
    }
    if (status >= 0 && mode === 0) {
        cm.dispose();
        return;
    }
    if (mode === 1) {
        status++;
    } else {
        status--;
    }

    if (status === 0) {
        var text = "#e#r BeiDouMS 真漂亮整形医院（感谢ColaMintヾ小明湖畔的分享）#k#n\r\n";
        text += "我的鼻子是假的，我的眼睛是假的，但我的美丽是真的！\r\n\r\n"
        var hairPageCount = Math.ceil(Object.keys(hairColors).length / HAIR_PAGE_SIZE);
        for (var page = 0; page < hairPageCount; page++) {
            text += "#L" + (HAIR_PAGE_SELECTION_BASE + page) + "#第" + (page + 1) + "批发型#l\t";
            if ((page + 1) % 3 === 0) {
                text += "\r\n";
            }
        }
        text += "\r\n";
        text += "#L20#第一批脸型#l\t#L21#第二批脸型（未开放）#l\r\n";
        text += "#L30#发色#l\r\n";
        text += "#L40#脸色#l\r\n";
        text += "#L50#肤色#l\r\n";
        cm.sendSimple(text);
    } else if (status === 1) {
        if (selection >= HAIR_PAGE_SELECTION_BASE && selection < HAIR_PAGE_SELECTION_BASE + Math.ceil(Object.keys(hairColors).length / HAIR_PAGE_SIZE)) {
            beauty = 1;
            var currentColor = cm.getPlayer().getHair() % 10;
            var baseHairs = Object.keys(hairColors);
            var hairPage = selection - HAIR_PAGE_SELECTION_BASE;
            for (var i = hairPage * HAIR_PAGE_SIZE; i < (hairPage + 1) * HAIR_PAGE_SIZE && i < baseHairs.length; ++i) {
                baseHair = baseHairs[i];
                if (hairColors[baseHair].indexOf(currentColor) >= 0) {
                    newHairs.push(parseInt(baseHair) + currentColor)
                } else {
                    newHairs.push(parseInt(baseHair) + hairColors[baseHair][0])
                }
                if (newHairs.length >= HAIR_PAGE_SIZE) {
                    break;
                }
            }
            cm.sendStyle("挑选一款发型吧！", newHairs);
        } else if (selection >= 20 && selection < 30) {
            beauty = 2;
            var currentColor = cm.getPlayer().getFace() % 1000 - (cm.getPlayer().getFace() % 100);
            var baseFaces = Object.keys(faceColors);
            for (var i = (selection % 10) * 128; i < (selection % 10 + 1) * 128 && i < baseFaces.length; ++i) {
                baseFace = baseFaces[i];
                if (faceColors[baseFace].indexOf(currentColor) >= 0) {
                    newFaces.push(parseInt(baseFace) + currentColor)
                } else {
                    newFaces.push(parseInt(baseFace) + faceColors[baseFace][0])
                }
            }
            cm.sendStyle("挑选一款脸型吧！", newFaces);
        } else if (selection === 30) {
            beauty = 1;
            var currentBaseHair = parseInt(cm.getPlayer().getHair() / 10) * 10;
            for (var i = 0; i < hairColors[currentBaseHair].length; i++) {
                newHairs.push(currentBaseHair + hairColors[currentBaseHair][i]);
            }
            cm.sendStyle("挑选一款发色吧！", newHairs);
        } else if (selection === 40) {
            beauty = 2;
            var currentColor = cm.getPlayer().getFace() % 1000 - (cm.getPlayer().getFace() % 100);
            var currentBaseFace = cm.getPlayer().getFace() - currentColor;
            for (var i = 0; i < faceColors[currentBaseFace].length; i++) {
                newFaces.push(currentBaseFace + faceColors[currentBaseFace][i]);
            }
            cm.sendStyle("挑选一款脸色吧！", newFaces);
        } else if (selection === 50) {
            beauty = 3;
            cm.sendStyle("挑选一款肤色吧！", skins);
        }
    } else if (status === 2) {
        if (beauty == 1) {
            cm.setHair(newHairs[selection]);
        } else if (beauty == 2) {
            cm.setFace(newFaces[selection]);
        } else if (beauty == 3) {
            cm.setSkin(skins[selection]);
        }
    }
}
