var hairnew = Array();

function pushIfItemExists(array, itemid) {
    if ((itemid = cm.getCosmeticItem(itemid)) != -1 && !cm.isCosmeticEquipped(itemid)) {
        array.push(itemid);
    }
}
function start() {
    status = -1;
    action(1, 0, 0);
}

function buildHairList(startIndex, endIndex) {
    hairnew = Array();
    var currentColor = parseInt(cm.getPlayer().getHair() % 10);
    for (var i = startIndex; i < endIndex && i < hairCatalog.length; i++) {
        pushIfItemExists(hairnew, hairCatalog[i] + currentColor);
    }
}

function sendHairPageMenu() {
    var pageCount = Math.ceil(hairCatalog.length / HAIR_PAGE_SIZE);
    var text = "请选择发型批次。全部发型均提供图片预览。\r\n\r\n";
    for (var page = 0; page < pageCount; page++) {
        var first = page * HAIR_PAGE_SIZE + 1;
        var last = Math.min((page + 1) * HAIR_PAGE_SIZE, hairCatalog.length);
        text += "#L" + (HAIR_PAGE_SELECTION_BASE + page) + "#第" + (page + 1) + "批（" + first + "-" + last + "，有预览）#l";
        text += (page + 1) % 2 == 0 ? "\r\n" : "\t";
    }
    cm.sendSimple(text);
}

function applySelectedHair(hairId) {
    var isGM = cm.getPlayer().isGM();
    if (isGM || cm.haveItem(5150044)) {
        if (!isGM) {
            cm.gainItem(5150044, -1);
        }
        cm.setHair(hairId);
        cm.sendOk("享受你的新发型吧!");
    } else {
        cm.sendOk("嗯…看起来你没有我们指定的会员卡。。。没有它恐怕我不能给你理发。对不起。。。");
    }
    cm.dispose();
}

function action(mode, type, selection) {
    if (mode < 1) {
        cm.dispose();
        return;
    }

    status++;

    if (status == 0) {
        var gmHint = cm.getPlayer().isGM() ? "  #r（GM 免费）#k" : "";
        cm.sendSimple("#p1012117#是世界上最迷人、最时尚的造型师。如果你想找最好看的发型，就别再找别人了!\r\n#L0##i5150040# #t5150040#  随机发型" + gmHint + "#l\r\n#L1##i5150044# #t5150044#  自选发型" + gmHint + "#l");
    } else if (status == 1) {
        if (selection == 0) {
            beauty = 1;
            cm.sendYesNo(cm.getPlayer().isGM()
                ? "GM 可免费更换随机发型。确定要继续吗？结果是随机的！"
                : "如果你使用这个普通会员卡，你的头发可能会变成一个随机的新外观。你还想用#b#t5150040##k做头发吗？我无论如何都会为你做的。但别忘了，结果随机的！");
        } else if (selection == 1) {
            beauty = 2;
            sendHairPageMenu();
        } else {
            cm.dispose();
        }
    } else if (status == 2) {
        if (beauty == 1) {
            var isGM = cm.getPlayer().isGM();
            if (isGM || cm.haveItem(5150040)) {
                buildHairList(0, hairCatalog.length);
                if (hairnew.length == 0) {
                    cm.sendOk("当前没有可用的新发型。");
                } else {
                    if (!isGM) {
                        cm.gainItem(5150040, -1);
                    }
                    cm.setHair(hairnew[Math.floor(Math.random() * hairnew.length)]);
                    cm.sendOk("享受你的新发型吧!");
                }
            } else {
                cm.sendOk("嗯…看起来你没有我们指定的会员卡。。。没有它恐怕我不能给你理发。对不起。。。");
            }
            cm.dispose();
        } else if (beauty == 2) {
            var page = selection - HAIR_PAGE_SELECTION_BASE;
            var pageCount = Math.ceil(hairCatalog.length / HAIR_PAGE_SIZE);
            if (page >= 0 && page < pageCount) {
                buildHairList(page * HAIR_PAGE_SIZE, (page + 1) * HAIR_PAGE_SIZE);
                if (hairnew.length == 0) {
                    cm.sendOk("这一批没有可用的新发型。");
                    cm.dispose();
                } else {
                    var prompt = cm.getPlayer().isGM()
                        ? "GM 可免费更换发型。请选择最能给你带来快乐的款式。"
                        : "使用高级会员卡，你可以选择你的发型。请选择最能给你带来快乐的款式。";
                    cm.sendStyle(prompt, hairnew);
                }
            } else {
                cm.dispose();
            }
        } else {
            cm.dispose();
        }
    } else if (status == 3 && beauty == 2) {
        if (selection < 0 || selection >= hairnew.length) {
            cm.dispose();
            return;
        }
        applySelectedHair(hairnew[selection]);
    } else {
        cm.dispose();
    }
}
