bool WeatherSway_IsLeafreTreeObject(const wchar_t* sOS, const wchar_t* sL0,
                                    const wchar_t* sL1) {
    if (!sOS || !sL0 || !sL1 || _wcsicmp(sL1, L"nature1") != 0) {
        return false;
    }
    return (_wcsicmp(sOS, L"acc6") == 0 && _wcsicmp(sL0, L"minar") == 0)
        || (_wcsicmp(sOS, L"dungeon3") == 0 && _wcsicmp(sL0, L"dragonRoad") == 0);
}

bool WeatherSway_IsLeafreTreeBack(const wchar_t* sBS, int nNo) {
    if (!sBS || _wcsicmp(sBS, L"minar") != 0) return false;
    // These are the four large leafy tree layers used by Leafre town.  Keep the
    // selection narrow: `minar` also contains sky, rock and architecture backs.
    return nNo == 8 || nNo == 9 || nNo == 11 || nNo == 14;
}

void WeatherSway_ReplaceLeafreBack(const IWzGr2DLayerPtr& pLayer) {
    if (!pLayer || !WeatherCanvas_Probe()) return;
    try {
        IWzCanvasPtr src = pLayer->Getcanvas();
        if (!src) return;
        const int w = src->width, h = src->height;
        if (w <= 0 || h <= 0 || w > 900 || h > 640) return;

        // The lower trunk remains still.  The back layer itself stays intact, so its
        // native parallax and camera tracking continue to be owned by the engine.
        const int pivot = (int)((float)h * 0.68f);
        const float leanMax = 0.024f;      // calmer than foreground foliage
        const int pad = (int)(leanMax * (float)h) + 3;
        IWzCanvasPtr frame[5];
        for (int i = 0; i < 5; ++i) {
            const float f = (float)(i - 2) * 0.5f;
            PROJECT cfg{};
            cfg.fLean = leanMax * f;
            cfg.fSquash = 1.0f;
            cfg.fAlpha = 1.0f;
            cfg.bKeepColour = true;
            cfg.nPadOverride = pad;
            cfg.nPivotRow = pivot;
            cfg.nClearX = -1;
            cfg.nClearY = -1;
            POINT anchor{};
            int actualPivot = pivot;
            frame[i] = WeatherCanvas_Project(src, cfg, &anchor, &actualPivot);
            if (!frame[i]) return;
            // The added pad must not shift the tree inside its existing parallax layer.
            frame[i]->cx = src->cx + anchor.x;
            frame[i]->cy = src->cy + anchor.y - actualPivot;
        }

        // A map back begins with one static canvas.  Replacing that set on the SAME
        // layer (rather than creating world-space overlays) is what preserves parallax.
        try { pLayer->Animate(GA_STOP); } catch (const _com_error&) {}
        for (int i = 7; i >= 0; --i) {
            try { pLayer->RemoveCanvas(i); } catch (const _com_error&) {}
        }
        for (int i = 0; i < 5; ++i) {
            pLayer->InsertCanvas(frame[i], 750, 255, 255);
        }
        pLayer->Animate(GA_REPEAT);
    } catch (const _com_error&) {
        // Leave the original back untouched if the client declines a canvas operation.
    }
}

static unsigned long long ExtraHash(const EXTRASWAY& e) {
    unsigned long long h = 1469598103934665603ULL;
    h = ClumpHashPart(h, e.sOS);
    h = ClumpHashPart(h, e.sL0);
    h = ClumpHashPart(h, e.sL1);
    h = ClumpHashPart(h, e.sL2);
    return h;
}

static unsigned long long DeadOverlayHash(const DEADOVERLAY& e) {
    unsigned long long h = 1469598103934665603ULL;
    h = ClumpHashPart(h, e.sOS);
    h = ClumpHashPart(h, e.sL0);
    h = ClumpHashPart(h, e.sL1);
    h = ClumpHashPart(h, e.sL2);
    return h;
}

static const CLUMPDEF* ClumpsForHash(unsigned long long uWant) {
    static unsigned long long s_a[_countof(kClumps)];
    static bool s_bReady = false;
    if (!s_bReady) {
        for (size_t i = 0; i < _countof(kClumps); ++i) {
            unsigned long long h = 1469598103934665603ULL;
            h = ClumpHashPart(h, kClumps[i].sOS);
            h = ClumpHashPart(h, kClumps[i].sL0);
            h = ClumpHashPart(h, kClumps[i].sL1);
            h = ClumpHashPart(h, kClumps[i].sL2);
            s_a[i] = h;
        }
        s_bReady = true;
    }
    if (!uWant) {
        return nullptr;
    }
    for (size_t i = 0; i < _countof(kClumps); ++i) {
        if (s_a[i] == uWant) {
            return &kClumps[i];
        }
    }
    return nullptr;
}

