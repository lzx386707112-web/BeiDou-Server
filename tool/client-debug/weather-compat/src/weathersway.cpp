// Hashed the same way Weather_ObjPathHash does it, so a row can be found from an object
// without either side holding a WZ string. Built once, on first use.
static unsigned long long ClumpHashPart(unsigned long long h, const wchar_t* s) {
    h ^= 0x2Fu; h *= 1099511628211ULL;
    for (; s && *s; ++s) {
        wchar_t c = *s;
        if (c >= L'A' && c <= L'Z') c = (wchar_t)(c - L'A' + L'a');
        h ^= (unsigned long long)c;
        h *= 1099511628211ULL;
    }
    return h;
}

// Props that are not filed as foliage but move like it, and HOW FAR DOWN they bend.
//
// fPivotFrac is where the bend starts, as a fraction of the sprite's height: 1.0 is the
// base (an ordinary plant, rooted at the ground), 0.55 means the bottom 55% is rigid and
