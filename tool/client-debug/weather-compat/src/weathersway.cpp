// Foliage that BENDS rather than slides.
//
// The first version moved the whole sprite a couple of pixels, which slid the base along
// the ground with the top: a plant on a conveyor belt rather than a plant in the wind.
// A real sway keeps the base planted and leans everything above it, which is a SHEAR, and
// IWzGr2DLayer has no shear. So the lean lives in the pixels, generated by
// weathercanvas.cpp from the object's own sprite.
//
// HOW THE FRAMES WORK
// -------------------
// Each object gets SWAY_FRAMES sheared copies of itself, spanning the full storm lean from
// hard left to hard right. Calm weather cycles through the MIDDLE few; a storm uses the
// whole set. So the strength of the wind costs nothing at runtime: it is which frames get
// shown, not a regeneration.
//
// Every frame is generated at the SAME canvas size, padded for the widest lean, so
// switching between them cannot move the sprite. That is why the pad is passed in rather
// than derived per frame.
//
// ONE LAYER PER FRAME, and only one visible at a time. The alternative is swapping the
// canvas on a single layer, which means calling RemoveCanvas and InsertCanvas on a layer
// the ENGINE owns, several times a second, forever. Toggling `visible` is one property
// write and cannot leave a map object with no canvas at all.
//
// The original object layer is HIDDEN, not modified. If anything here fails the worst case
// is putting its visibility back, which is also exactly what teardown does.

// ODD, AND THAT IS NOT A PREFERENCE. The shear for frame i is (i - n/2) / (n/2), so an
// EVEN count has no frame at zero: at 10 the range comes out -1.0 .. +0.8, every plant
// leans further left than right, and calm weather centres on a frame that is already
// tilted. 11 is the odd count next to the 10 that was asked for.
#define SWAY_FRAMES       11      // odd, so there is a true upright in the middle
#define SWAY_FRAMES_BIG    7      // ...and fewer for a big sprite, see the budget below
#define SWAY_BIG_PIXELS  18000    // above this a sprite counts as big
// Objects that may sway, per field.
//
// 72 was cutting Henesys by 18 plants: it generates 90 sway entries and the loop that
// builds them stops at the cap, in object order, so the last fifth of the map's greenery
// simply never moved. Clump splitting made it worse by design -- four mushrooms in one
// sprite are four entries now, not one.
//
// The MEMORY limiter is SWAY_PIXEL_BUDGET, and all 90 of Henesys' entries fit inside it at
// 71%. This count was a second, blunter limit measuring the wrong thing: a hundred small
// plants cost less than three bushes. 128 leaves the budget as the only real ceiling,
// which is where the decision belongs.
#define SWAY_MAX_OBJ     128
#define SWAY_MAX_PIXELS  (360 * 320)   // one object may not be larger than this

// TOTAL generated pixels allowed across every swaying object on a map: 8M pixels at 4
// bytes each, so about 32 MB. Frames are the whole cost of this feature: nine copies of a
// 290x239 shrub is 2.5 MB on its own, and a dense map would happily ask for hundreds. The
// budget is what makes raising the size ceiling safe.
//
// Raised from 6M when bushes were admitted: Henesys alone was already at 77% of the old
// figure and the bush took it to 95%, which leaves no room for a denser map and makes the
// budget cut -- which drops objects SILENTLY in a release build -- a live risk rather than
// a backstop.
//
// The honest fix is not a bigger number. Every INSTANCE builds its own frames, so the 18
// copies of acc1/grassySoil/nature/13 in Henesys generate 18 identical frame sets and
// account for roughly 44% of the whole budget on that map by themselves. Layers can share
// a canvas, so caching frames per (sprite, clump) and pointing every instance at the same
// set would cut this by the instance count. That is the change to make if this is ever
// tight again.
#define SWAY_PIXEL_BUDGET (8 * 1024 * 1024)
// MEASURED OFF A REFERENCE CAPTURE, rather than guessed.
//
// Tools note: 137 frames of a 30fps capture were tracked by the sunflower head's centroid
// (Tools has no script for it; it was a one-off crop-and-centroid over the extracted
// frames). The head travelled 13.2 px peak to peak on a plant 221 px tall -- +-0.030 of
// its own height -- on a clean sine with peaks 39 frames apart, i.e. a 1.30 s period.
//
// So calm wants +-0.030 and a 1.3 s cycle. Calm is SWAY_CALM_FRAC of SWAY_LEAN_MAX, so
// 0.50 x 0.060 lands exactly on it and leaves storm at 0.060, twice calm, which is the
// separation the old 3/4 span had lost.
//
// A FRACTION, not a frame count, and that is load bearing. It used to be "2 frames either
// side of upright", which silently encoded SWAY_FRAMES = 9: raising the frame count makes
// each step smaller, so the same 2 steps would have quietly cut the calm amplitude by a
// third and un-calibrated it from the reference above. Expressed as a fraction of the
// half-range, the amplitude survives any frame count and only the resolution changes.
//
// THIS SPEEDS THE SWAY UP, reversing an earlier "much slower would look better". That
// request came before the pivot fix, when plants were shearing about their waists: what
// read as too much movement was mostly the distortion, not the rate. The reference is the
// better authority now, but the two numbers to move back are right here.
#define SWAY_LEAN_MAX   0.060f    // storm lean; calm is half of it, see the span below
// The least a plant's top should travel at full lean, in pixels. Below this the motion is
// there in the numbers and invisible on screen.
#define SWAY_MIN_TRAVEL      5.0f
// ...but a 12 px sprite must not be scaled up 4x into a windscreen wiper.
#define SWAY_SMALL_BOOST_MAX 2.2f
#define SWAY_CALM_FRAC     0.50f  // of the half-range, in fair weather
#define SWAY_EXPOSED_FRAC  0.75f  // ...for the third of plants that read as more exposed
// High wind used to take the WHOLE half-range, i.e. the full SWAY_LEAN_MAX. That is the
// most the generated frames can do, so it also meant a storm was pinned at the ceiling
// with nothing above it; backing off leaves the top of the range as headroom and stops a
// gale reading as every plant slapping its own limit.
#define SWAY_ROUGH_FRAC    0.85f
// Slowed hard. A plant in a breeze moves at the pace of the breeze, and at 2.6 s a
// calm bush was ticking over like a metronome; 6.2 s reads as air moving rather than
// as an animation playing. Storm goes 0.85 -> 2.4 s for the same reason -- fast enough
// to look driven, slow enough not to vibrate.
#define SWAY_PERIOD_CALM 1300.0f
#define SWAY_PERIOD_ROUGH 700.0f
// Rope and ladder move SLOWLY, on their own clock, about two and a half times the
// foliage period. A heavy pendulum has a long period, so a wooden ladder that moves
// little but quickly reads as jitter, while the same small movement drawn out over six
// seconds reads as weight. That is the whole difference and it is timing, not distance.
#define SWAY_PERIOD_ROPE_CALM  6400.0f
#define SWAY_PERIOD_ROPE_ROUGH 2400.0f
// Objects to build per frame. Forty objects at nine frames each is 360 canvas
// generations, and doing them all on the frame the map loads is a visible stall.
#define SWAY_BUILD_PER_FRAME 2

// Two rope or ladder segments closer than this horizontally are one structure.
//
// A long ladder is not one object: it is a column of segments stacked end to end. Swayed
// independently they slide apart at every joint, because each restarts its lean from its
// own base and each is on its own phase. Grouping fixes both: one phase for the column,
// and each segment leaning from the bottom of the WHOLE column via nBaseOffset.
#define SWAY_STACK_DX      30

// How much of a rope hangs rigid below its anchor before it starts to bend.
//
// A rope tied to a stake does not curve at the knot: the top is held straight and the free
// length below it swings. 0.5 puts the bend in the bottom half, which is what a rope
// hanging off a post actually does. Measured down the whole COLUMN, so a long rope made of
// several segments has one rigid head rather than a stiff patch at every joint.
#define SWAY_ROPE_RIGID_FRAC 0.5f

