def resolve(cell):
    missing_mark = "（缺）" in cell
    base = cell.replace("（缺）", "").strip()
    if base in EXPLICIT:
        return [i for i in EXPLICIT[base] if i in NAME], missing_mark
    if base in index:
        return sorted(index[base]), missing_mark
    if base.endswith("武器") or base.endswith("装备"):
        raw = base[:-2]
        cands = []
        if raw in WEAPON_PREFIX:
            cands.append(WEAPON_PREFIX[raw])
        cands.append(raw)
        for word in JOB_WORD:
            if raw.endswith(word) and raw[:-len(word)]:
                cands.append(raw[:-len(word)])
        job = job_of(raw)
        for prefix in cands:
            hits = [it["id"] for it in items
                    if CATEGORY.get(it["id"]) == "Weapon" and NAME.get(it["id"], "").startswith(prefix)
                    and (job is None or int(str(it["id"])[:3]) in JOB_RANGES[job])]
            if hits:
                return sorted(set(hits)), missing_mark
    return [], missing_mark


